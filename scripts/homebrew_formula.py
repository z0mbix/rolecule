"""Generate the tap formula from verified, published Rolecule release archives."""

import argparse
import hashlib
import re
from pathlib import Path


STABLE_TAG = re.compile(
    r"v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)"
    r"(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?"
)


def stable_version(tag):
    if not STABLE_TAG.fullmatch(tag):
        raise ValueError("Homebrew requires a stable vMAJOR.MINOR.PATCH release tag")
    return tag[1:]


def validate_release(tag, release, latest):
    if release["tagName"] != tag or release["isDraft"]:
        raise ValueError("Homebrew requires a published release matching the requested tag")
    if release["isPrerelease"]:
        return False
    stable_version(tag)
    if tag != latest:
        raise ValueError(f"Refusing to replace the tap with a release other than {latest}")
    return True


def homebrew_formula(tag, directory):
    version = stable_version(tag)
    checksums = {}
    for line in (directory / f"rolecule_{version}_SHA256SUMS").read_text().splitlines():
        digest, filename = line.split()
        if filename in checksums:
            raise ValueError(f"Duplicate checksum for {filename}")
        checksums[filename] = digest

    platforms = []
    for system, homebrew_system in (("darwin", "macos"), ("linux", "linux")):
        architectures = []
        for arch, homebrew_arch in (("arm64", "arm"), ("amd64", "intel")):
            filename = f"rolecule_{version}_{system}_{arch}.tar.gz"
            digest = hashlib.sha256((directory / filename).read_bytes()).hexdigest()
            if checksums.get(filename) != digest:
                raise ValueError(f"Missing or mismatched checksum for {filename}")
            architectures.append(f'''    on_{homebrew_arch} do
      url "https://github.com/z0mbix/rolecule/releases/download/{tag}/{filename}"
      sha256 "{digest}"
    end''')
        platforms.append(f"  on_{homebrew_system} do\n" + "\n\n".join(architectures) + "\n  end")

    platform_blocks = "\n\n".join(platforms)
    return f'''# Generated by z0mbix/rolecule scripts/homebrew_formula.py.
class Rolecule < Formula
  desc "Test Ansible roles in Docker or Podman containers"
  homepage "https://github.com/z0mbix/rolecule"
  license "GPL-3.0-only"

{platform_blocks}

  def install
    bin.install "rolecule"
    doc.install "README.md"
  end

  test do
    assert_equal "rolecule {version}", shell_output("#{{bin}}/rolecule version").strip
    assert_match "ansible roles", shell_output("#{{bin}}/rolecule --help")
  end
end
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tag")
    parser.add_argument("release_directory", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    formula = homebrew_formula(args.tag, args.release_directory)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(formula)


if __name__ == "__main__":
    main()
